.text
.globl main

# =============================================================================
# ENTRY
# =============================================================================
main:
    addi x31, x0, 0
    j TEST_BEQ_TAKEN

# =============================================================================
# FAIL HANDLER (NO LOOPS)
# =============================================================================
FAIL:
    addi x31, x31, 1
    j HALT

# =============================================================================
# TEST 1: BEQ TAKEN
# =============================================================================
TEST_BEQ_TAKEN:
    addi x1, x0, 5
    addi x2, x0, 5
    beq  x1, x2, BEQ_TAKEN_OK
    j FAIL

BEQ_TAKEN_OK:
    j TEST_BEQ_NOTTAKEN

# =============================================================================
# TEST 2: BEQ NOT TAKEN
# =============================================================================
TEST_BEQ_NOTTAKEN:
    addi x5, x0, 0
    addi x1, x0, 5
    addi x2, x0, 6
    beq  x1, x2, FAIL

    addi x5, x5, 1
    addi x6, x0, 1
    bne  x5, x6, FAIL

    j TEST_BNE_TAKEN

# =============================================================================
# TEST 3: BNE TAKEN
# =============================================================================
TEST_BNE_TAKEN:
    addi x1, x0, 3
    addi x2, x0, 7
    bne  x1, x2, BNE_TAKEN_OK
    j FAIL

BNE_TAKEN_OK:
    j TEST_BLT_TAKEN

# =============================================================================
# TEST 4: BLT TAKEN
# =============================================================================
TEST_BLT_TAKEN:
    addi x1, x0, -1
    addi x2, x0, 1
    blt  x1, x2, BLT_TAKEN_OK
    j FAIL

BLT_TAKEN_OK:
    j TEST_BLT_NOTTAKEN

# =============================================================================
# TEST 5: BLT NOT TAKEN
# =============================================================================
TEST_BLT_NOTTAKEN:
    addi x9, x0, 0
    addi x1, x0, 1
    addi x2, x0, -1
    blt  x1, x2, FAIL

    addi x9, x9, 1
    addi x10, x0, 1
    bne  x9, x10, FAIL

    j TEST_BGE_TAKEN

# =============================================================================
# TEST 6: BGE TAKEN
# =============================================================================
TEST_BGE_TAKEN:
    addi x1, x0, 5
    addi x2, x0, 5
    bge  x1, x2, BGE_TAKEN_OK
    j FAIL

BGE_TAKEN_OK:
    j TEST_BLTU_TAKEN

# =============================================================================
# TEST 7: BLTU TAKEN
# =============================================================================
TEST_BLTU_TAKEN:
    addi x1, x0, 1
    addi x2, x0, -1
    bltu x1, x2, BLTU_TAKEN_OK
    j FAIL

BLTU_TAKEN_OK:
    j TEST_BGEU_TAKEN

# =============================================================================
# TEST 8: BGEU TAKEN
# =============================================================================
TEST_BGEU_TAKEN:
    addi x1, x0, -1
    addi x2, x0, 1
    bgeu x1, x2, BGEU_TAKEN_OK
    j FAIL

BGEU_TAKEN_OK:
    j TEST_JAL

# =============================================================================
# TEST 9: JAL
# =============================================================================
TEST_JAL:
    jal  x13, JAL_TARGET
JAL_RETURN:
    addi x14, x0, 1
    j TEST_JALR

JAL_TARGET:
    addi x23, x0, 1
    j JAL_RETURN

# =============================================================================
# TEST 10: JALR
# =============================================================================
TEST_JALR:
    la   x1, JALR_TARGET
    jalr x15, x1, 0
JALR_RETURN:
    addi x16, x0, 1
    j DONE

JALR_TARGET:
    addi x24, x0, 1
    j JALR_RETURN

# =============================================================================
# DONE
# =============================================================================
DONE:
    bne x31, x0, FAIL
    addi x31, x0, 0
    j HALT

# =============================================================================
# SINGLE HALT (NO FALLTHROUGH, NO LOOP)
# =============================================================================
HALT:
    wfi